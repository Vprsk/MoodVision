"""Форматирование времени для UI (ММ:СС / Ч:ММ:СС).

Общая утилита для страниц «Файлы», «Потоки» и таймлайна эпизодов, чтобы
не дублировать один и тот же код форматирования в нескольких виджетах.
"""


def format_hms(seconds: float) -> str:
    """Форматирует секунды в «ММ:СС» (или «Ч:ММ:СС» для длинных видео)."""
    seconds = max(0, int(seconds))
    h, rem = divmod(seconds, 3600)
    m, s = divmod(rem, 60)
    if h > 0:
        return f"{h}:{m:02d}:{s:02d}"
    return f"{m:02d}:{s:02d}"
